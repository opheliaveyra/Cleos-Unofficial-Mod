#!/usr/bin/env python3
"""Rebuild independent SVG sources and the Compose vector registry from catalog.py."""
from pathlib import Path
from catalog import ICONS, ALIASES, COLORS
ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'app/src/main/java/com/cleo/cleos/ui/icons'
OUT.mkdir(parents=True, exist_ok=True)
SVG = ROOT / 'docs/paper-icons/svg'
SVG.mkdir(parents=True, exist_ok=True)
header = '''// Generated by tools/paper-icons/generate.py; edit catalog.py instead.
package com.cleo.cleos.ui.icons

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.StrokeCap
import androidx.compose.ui.graphics.StrokeJoin
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.PathParser
import androidx.compose.ui.unit.dp

/** Original, independently drawn 24dp paper assets; no bitmap or runtime dependency. */
internal object PaperVectors {
    private data class Layer(val data: String, val fill: Color?, val outline: Boolean)
    private val ink = Color(0xFF514960)
    private val paper = Color(0xFFFFF9EF)
    private val lilac = Color(0xFFDED4F1)
    private val blue = Color(0xFFC9DEEA)
    private val drawings = mapOf(
'''
rows=[]
for key, paths in ICONS.items():
    rows.append('        "'+key+'" to listOf(\n'+''.join('            Layer("'+d+'", '+('null' if fill=='none' else fill)+', '+str(stroke).lower()+'),\n' for d,fill,stroke in paths)+'        ),\n')
    layers=[]
    for index, (d,fill,stroke) in enumerate(paths):
        # Light perimeter separates the pencil from busy/dark wallpaper.
        if stroke: layers.append(f'<path d="{d}" fill="none" stroke="#FFF9EF" stroke-width="2.3"/>')
        layers.append(f'<path d="{d}" fill="{COLORS[fill]}" fill-opacity="{0.78 if fill in ('lilac', 'blue') else 1}" stroke="'+('#514960' if stroke else 'none')+'" stroke-width="1.25"/>')
        if fill == 'paper':
            clip=f'grain{index}'
            layers.append(f'<defs><clipPath id="{clip}"><path d="{d}"/></clipPath></defs><path clip-path="url(#{clip})" d="M6 7 l1.4 -.2 M14 8 l1 -.15 M8 18 l1.5 -.2 M16 16 l1 -.15" stroke="#514960" opacity=".14" stroke-width=".3"/>')
    svg='<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24"><g stroke-linecap="round" stroke-linejoin="round">'+''.join(layers)+'</g></svg>\n'
    (SVG/(key+'.svg')).write_text(svg)
footer='''    )
    private val aliases = mapOf(
'''
for key, aliases in ALIASES.items():
    for alias in aliases.split(): footer += f'        "{alias}" to "{key}",\n'
footer+='''    )
    // Lazy initialization happens once, on the UI thread; no per-frame parsing/cache writes.
    private val vectors: Map<String, ImageVector> by lazy {
        drawings.mapValues { (key, layers) ->
            ImageVector.Builder("Paper.$key", 24.dp, 24.dp, 24f, 24f, autoMirror = key == "send").apply {
                for (layer in layers) {
                    val nodes = PathParser().parsePathString(layer.data).toNodes()
                    if (layer.outline) addPath(
                        pathData = nodes, fill = null, stroke = SolidColor(paper),
                        strokeLineWidth = 2.3f, strokeLineCap = StrokeCap.Round,
                        strokeLineJoin = StrokeJoin.Round,
                    )
                    addPath(
                        pathData = nodes, fill = layer.fill?.let { SolidColor(it) },
                        fillAlpha = if (layer.fill == lilac || layer.fill == blue) 0.78f else 1f,
                        stroke = if (layer.outline) SolidColor(ink) else null,
                        strokeLineWidth = 1.25f, strokeLineCap = StrokeCap.Round,
                        strokeLineJoin = StrokeJoin.Round,
                    )
                    if (layer.fill == paper) {
                        addGroup(clipPathData = nodes)
                        addPath(
                            pathData = PathParser().parsePathString(
                                "M6 7 l1.4 -.2 M14 8 l1 -.15 M8 18 l1.5 -.2 M16 16 l1 -.15"
                            ).toNodes(),
                            fill = null, stroke = SolidColor(ink), strokeAlpha = 0.14f,
                            strokeLineWidth = 0.3f, strokeLineCap = StrokeCap.Round,
                        )
                        clearGroup()
                    }
                }
            }.build()
        }
    }
    fun replacement(original: ImageVector): ImageVector? =
        aliases[original.name.substringAfterLast('.')]?.let { vectors[it] }
}
'''
(OUT/'PaperVectors.kt').write_text(header+''.join(rows)+footer)
print(f'Generated {len(ICONS)} independent vectors, {sum(len(v.split()) for v in ALIASES.values())} aliases.')
